"""Generate docs/tutorial_quebec_idf.md (real ECCC data, real outputs, figures).

    python docs/scripts/tutorial_quebec_idf.py
"""

from __future__ import annotations

import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from tails.plotting import apply_axes_style, color  # noqa: E402

import tails  # noqa: E402
from tails.datasets import DURATION_TAGS, DURATIONS_H, load_eccc_quebec  # noqa: E402
from tails.idf import IDFData, fit_idf, scaling_test  # noqa: E402

DOCS = Path(__file__).parents[1]
IMG = DOCS / "img"
IMG.mkdir(exist_ok=True)
out = []
w = out.append

# ECCC Table 2a, 100-year Gumbel amounts (mm) for 701S001, IDF v3.40 (2025-12-05), parsed with
# tails.datasets.parse_eccc_return_levels from idf_v3-40_2025_12_5_701_QC_701S001_QUEBEC_JEAN_LESAGE_INTL.txt
ECCC_100 = {"5min": 17.3, "10min": 23.8, "15min": 28.9, "30min": 39.0, "1h": 50.5, "2h": 60.1, "6h": 75.4, "12h": 89.3, "24h": 104.1}


def md(df, fmt="{:.2f}"):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: fmt.format(v) if np.isfinite(v) else "–")
    return df.to_markdown(index=False)


w("# Tutorial: IDF curves for Québec City, end to end\n")
w("*Generated by `docs/scripts/tutorial_quebec_idf.py` from real ECCC data; every number below is computed, none typed in.*\n")
w("We estimate rainfall intensity–duration–frequency (IDF) curves for **Québec City – Jean Lesage "
  "International Airport (ECCC station 701S001, 1961–2024)**, compare models and their uncertainty, "
  "check for a trend, and then fit **all 151 Québec stations at once**, from a list or from an xarray DataArray.\n")

# 1 data -------------------------------------------------------------------------------------------
w("## 1. Data\n")
w("ECCC's Engineering Climate Datasets (IDF v3.40, 2025-12-05) give, for each station, the annual "
  "maximum rainfall *depth* for 9 durations. `tails` bundles the Québec files and converts depths "
  "to intensities (mm/h):\n")
w("```python\nfrom tails.idf import IDFData\ndata = IDFData.from_eccc(\"701S001\")\n```\n")
data = IDFData.from_eccc("701S001")
df = data.to_dataframe()
w(f"{data.n_years} years ({data.years.min()}–{data.years.max()}), {int(np.isnan(data.values).sum())} missing values. First rows (mm/h):\n")
w(md(df.head(5), "{:.1f}") + "\n")

# 2 per-duration GEV -------------------------------------------------------------------------------
w("## 2. One GEV per duration — nine fits in one call\n")
w("```python\nimport tails\nfit9 = tails.fit_gev(data.values.T)          # shape (9, 64): 9 series\nrl = fit9.return_level([100], ci=\"profile\")\n```\n")
fit9 = tails.fit_gev(data.values.T)
rl9 = fit9.return_level([100], ci="profile")
rl9d = fit9.return_level([100], ci="delta")
t9 = pd.DataFrame({
    "duration": data.tags,
    "shape ξ": fit9.params["shape"],
    "100-yr (mm/h)": rl9.estimate[:, 0],
    "profile 95% CI": [f"[{a:.1f}, {b:.1f}]" for a, b in zip(rl9.lower[:, 0], rl9.upper[:, 0])],
    "Wald 95% CI": [f"[{a:.1f}, {b:.1f}]" for a, b in zip(rl9d.lower[:, 0], rl9d.upper[:, 0])],
    "ECCC Gumbel": [ECCC_100[t] / d for t, d in zip(DURATION_TAGS, DURATIONS_H)],
})
w(md(t9) + "\n")
w("Profile-likelihood intervals are asymmetric (longer upper tails), as they should be for 100-year "
  "levels; Wald intervals are symmetric by construction. ECCC's published values use a Gumbel "
  "(ξ = 0) fit by moments.\n")

# 3 scaling test -----------------------------------------------------------------------------------
w("## 3. Which scaling model? (Scaling-model test)\n")
p_s, p_g = scaling_test(data, "simple"), scaling_test(data, "general")
w("```python\nfrom tails.idf import scaling_test\nscaling_test(data, \"simple\"), scaling_test(data, \"general\")\n```\n")
w(f"p-values: simple scaling **{p_s:.3g}**, general scaling (d-GEV) **{p_g:.3g}** "
  "(the Zolotarev approximation is only meaningful for small p-values). "
  + ("Simple scaling is rejected; we use the d-GEV.\n" if p_s < 0.05 else "Neither model is rejected at 5 %.\n"))

# 4 joint models -----------------------------------------------------------------------------------
w("## 4. d-GEV with and without cross-duration dependence\n")
w("```python\nfrom tails.idf import fit_idf\nind = fit_idf(data, \"general\")                       # independence (composite likelihood)\ngau = fit_idf(data, \"general\", \"matern\")             # Gaussian copula, Matérn on log-durations\nstu = fit_idf(data, \"general\", \"exponential\", \"t\", df=5)\n```\n")
ind = fit_idf(data, "general")
gau = fit_idf(data, "general", "matern")
stu = fit_idf(data, "general", "exponential", "t", df=5)
rows = []
for name, f in [("d-GEV, independent durations", ind), ("d-GEV + Matérn Gaussian copula", gau), ("d-GEV + exponential t(5) copula", stu)]:
    k = len(f.names)
    rows.append([name, *[f"{v:.4g}" for v in f.params[0][:5]], f.loglik[0], 2 * k - 2 * f.loglik[0]])
w(md(pd.DataFrame(rows, columns=["model", "μ₀", "σ₀", "ξ", "α", "δ", "log-lik", "AIC"])) + "\n")
w("The copula log-likelihoods are far higher: maxima of different durations in the same year are "
  "strongly dependent (the same storm), which the independence model ignores. (AIC of the independence "
  "model is not comparable — it is a composite likelihood.)\n")

# 5 uncertainty ------------------------------------------------------------------------------------
w("## 5. How uncertain is the 100-year intensity? Three answers, one arbiter\n")
w("The d-GEV fitted with independent durations needs a **sandwich (Godambe)** covariance; the "
  "naive Hessian pretends we have 9 × 64 independent observations. The copula model's Hessian is a "
  "proper likelihood Hessian. Because these Wald intervals can disagree by ~2×, `tails` adds a "
  "**parametric bootstrap from the joint (copula) model** — simulate 64 years of dependent "
  "9-duration maxima, refit, repeat 500 times, all refits in one batched call:\n")
w("```python\nind.quantile_ci(d, [100], method=\"hessian\")    # naive\nind.quantile_ci(d, [100], method=\"sandwich\")   # Godambe\ngau.quantile_ci(d, [100])                       # copula Hessian\ngau.quantile_ci(d, [100], method=\"bootstrap\", n_boot=500)\n```\n")
d = data.durations
t0 = time.perf_counter()
e_b, lo_b, hi_b = gau.quantile_ci(d, [100], method="bootstrap", n_boot=500)
t_boot = time.perf_counter() - t0
cis = {
    "d-GEV naive Wald": ind.quantile_ci(d, [100], method="hessian"),
    "d-GEV sandwich": ind.quantile_ci(d, [100], method="sandwich"),
    "copula Wald": gau.quantile_ci(d, [100]),
    "copula bootstrap": (e_b, lo_b, hi_b),
}
rows = []
for i, tag in enumerate(data.tags):
    r = [tag, ECCC_100[tag] / DURATIONS_H[i], cis["d-GEV naive Wald"][0][0, i, 0], cis["copula Wald"][0][0, i, 0]]
    for k, (e, lo, hi) in cis.items():
        r.append(f"[{lo[0, i, 0]:.1f}, {hi[0, i, 0]:.1f}]")
    rows.append(r)
w(md(pd.DataFrame(rows, columns=["duration", "ECCC Gumbel", "d-GEV estimate", "copula estimate", *cis.keys()])) + "\n")
w(f"The 500 bootstrap refits took {t_boot:.1f} s. Interval widths at 1 h: "
  + ", ".join(f"{k} {hi[0, 4, 0] - lo[0, 4, 0]:.1f}" for k, (e, lo, hi) in cis.items()) + " mm/h.\n")
w("Note that the pooled models give a lower 1-h 100-year intensity than both the single-duration GEV "
  "and ECCC's Gumbel value: the scaling relation borrows strength from other durations, and at "
  "Québec City the 1979 1-h storm sits above the pooled curve. Pooling reduces variance but can bias "
  "individual durations — exactly the trade-off a coverage study should quantify.\n")

fig, ax = plt.subplots(figsize=(7.4, 4.4))
x = np.arange(len(data.tags))
for j, (k, (e, lo, hi)) in enumerate(cis.items()):
    y = cis["copula Wald"][0][0, :, 0] if "copula" in k else ind.quantile(d, [100])[0, :, 0]
    ax.errorbar(
        x + (j - 1.5) * 0.16,
        y,
        yerr=[y - lo[0, :, 0], hi[0, :, 0] - y],
        fmt="o",
        ms=4,
        capsize=2.5,
        elinewidth=1.0,
        color=color(j),
        label=k,
        zorder=3,
    )
ax.scatter(
    x,
    [ECCC_100[t] / dd for t, dd in zip(DURATION_TAGS, DURATIONS_H)],
    marker="x",
    s=36,
    color="0.15",
    label="ECCC Gumbel",
    zorder=5,
)
ax.set_xticks(x, data.tags)
ax.set_yscale("log")
ax.set_ylabel("100-year intensity (mm/h)")
ax.set_xlabel("Duration")
ax.set_title("Québec City (701S001)\n100-year intensity and 95% intervals")
apply_axes_style(ax)
ax.legend(frameon=False, fontsize=8, loc="upper right")
fig.tight_layout()
fig.savefig(IMG / "quebec_100yr_ci.png", dpi=180, bbox_inches="tight")
w("![100-year intervals](img/quebec_100yr_ci.png)\n")

ax = gau.plot(
    periods=(2, 10, 25, 100),
    ci="hessian",
    title="Québec City (701S001)\nIDF curves, d-GEV with Matérn Gaussian copula",
)
ax.figure.savefig(IMG / "quebec_idf_curves.png", dpi=180, bbox_inches="tight")
w("![IDF curves](img/quebec_idf_curves.png)\n")

# 6 trend ------------------------------------------------------------------------------------------
w("## 6. Is there a trend? A non-stationary GEV for every duration at once\n")
w("```python\nyears = data.years - 2000.0\nst = tails.fit_gev(data.values.T)\nns = tails.fit_gev(data.values.T, loc=years)     # mu(t) = b0 + b1 (t − 2000)\nlr = 2 * (ns.loglik - st.loglik)                  # likelihood-ratio statistic, 1 df\n```\n")
yrs = data.years - 2000.0
ns = tails.fit_gev(data.values.T, loc=yrs)
from scipy.stats import chi2  # noqa: E402

lr = 2 * (ns.loglik - fit9.loglik)
w(md(pd.DataFrame({"duration": data.tags, "trend in μ (mm/h per decade)": 10 * ns.coef[:, 1],
                   "s.e.": 10 * ns.se[:, 1], "LR p-value": chi2.sf(lr, 1)}), "{:.3f}") + "\n")
w("A positive slope with a small p-value suggests the location of annual maxima is drifting up; "
  "with nine tests, apply a multiplicity correction before claiming one.\n")

# 7 all of Québec ----------------------------------------------------------------------------------
w("## 7. Scale up: d-GEV for all 151 Québec stations in one call\n")
q = load_eccc_quebec()
sts = []
for sid, g in q.groupby("station_id"):
    if g[DURATION_TAGS].notna().sum().min() >= 8:
        sts.append(IDFData.from_dataframe(g, year="year", depth=True, name=sid))
fit_idf(sts, "general")  # compile
t0 = time.perf_counter()
allq = fit_idf(sts, "general")
t_all = time.perf_counter() - t0
q100 = allq.quantile([1.0], [100])[:, 0, 0]
meta = q.drop_duplicates("station_id").set_index("station_id").loc[[s.name for s in sts]]
w("```python\nstations = [IDFData.from_dataframe(g, year=\"year\", depth=True, name=sid)\n            for sid, g in load_eccc_quebec().groupby(\"station_id\")]\nall_fit = fit_idf(stations, \"general\")   # one batched optimisation, missing values masked\n```\n")
w(f"{len(sts)} stations with ≥ 8 years for every duration were fitted in **{t_all:.2f} s** "
  f"(after compilation); {allq.converged.mean():.0%} converged. The 100-year 1-h intensity ranges "
  f"from {q100.min():.0f} to {q100.max():.0f} mm/h (median {np.median(q100):.0f}).\n")
# Map figure: pip install contextily pyproj  (not required to use tails)
import contextily as cx  # noqa: E402
from pyproj import Transformer  # noqa: E402

transformer = Transformer.from_crs("EPSG:4326", "EPSG:3857", always_xy=True)
mx, my = transformer.transform(meta.lon.to_numpy(), meta.lat.to_numpy())
fig, ax = plt.subplots(figsize=(7.2, 7.0))
sc = ax.scatter(
    mx,
    my,
    c=q100,
    cmap="viridis",
    s=32,
    edgecolors="white",
    linewidths=0.35,
    vmin=np.quantile(q100, 0.05),
    vmax=np.quantile(q100, 0.95),
    zorder=3,
)
cb = fig.colorbar(sc, ax=ax, shrink=0.65, pad=0.02)
cb.set_label("100-year 1-h intensity (mm/h)")
pad = 0.10
dx, dy = mx.max() - mx.min(), my.max() - my.min()
ax.set_xlim(mx.min() - pad * dx, mx.max() + pad * dx)
ax.set_ylim(my.min() - pad * dy, my.max() + pad * dy)
# CartoDB Positron now requires an API key (xyzservices injects ?key=).
# Esri's World Light Gray canvas is a similar light basemap and needs no key.
src = cx.providers.Esri.WorldGrayCanvas
credit = "Tiles © Esri — Esri, DeLorme, NAVTEQ"
cx.add_basemap(ax, source=src, crs="EPSG:3857", attribution=False)
ax.set_axis_off()
ax.set_title("d-GEV 100-year 1-h rainfall, Québec ECCC stations")
ax.text(
    0.0,
    -0.02,
    credit,
    transform=ax.transAxes,
    ha="left",
    va="top",
    fontsize=7,
    color="0.35",
    clip_on=False,
)
fig.tight_layout()
fig.savefig(IMG / "quebec_map_q100_1h.png", dpi=180, bbox_inches="tight")
w("![Québec map](img/quebec_map_q100_1h.png)\n")

# 8 xarray -----------------------------------------------------------------------------------------
w("## 8. The same fit on an xarray grid\n")
w("`tails.xarray.fit_idf` is that batched fit on a labelled array. The bundle stores depths in "
  "millimetres, so `depth=True` converts them to intensities (mm/h). The array below stacks Québec City, "
  "Montréal–Trudeau, and Sherbrooke A. This needs the xarray extra: `pip install \"rare-tails[xarray]\"`.\n")
w("```python\n"
  "import tails.xarray as tx\n"
  "from tails.datasets import DURATION_TAGS, load_eccc_quebec\n"
  "\n"
  "ids = [\"701S001\", \"702S006\", \"7028124\"]  # Québec City, Montréal–Trudeau, Sherbrooke A\n"
  "df = load_eccc_quebec()\n"
  "wide = df[df.station_id.isin(ids)].set_index([\"station_id\", \"year\"])[DURATION_TAGS]\n"
  "da = wide.to_xarray().to_array(\"duration\").rename(\"depth_mm\").reindex(station_id=ids)\n"
  "idf = tx.fit_idf(da, year=\"year\", duration=\"duration\", depth=True, marginal=\"general\")\n"
  "q = tx.idf_quantile(idf, [1.0, 24.0], [100])\n"
  "```\n")
import tails.xarray as tx  # noqa: E402

_ids = ["701S001", "702S006", "7028124"]
_names = {"701S001": "Québec City – Jean Lesage", "702S006": "Montréal–Trudeau", "7028124": "Sherbrooke A"}
_wide = q[q.station_id.isin(_ids)].set_index(["station_id", "year"])[DURATION_TAGS]
_da = _wide.to_xarray().to_array("duration").rename("depth_mm").reindex(station_id=_ids)
_idf = tx.fit_idf(_da, year="year", duration="duration", depth=True, marginal="general")
_qq = tx.idf_quantile(_idf, [1.0, 24.0], [100]).sel(period=100)
_show = pd.DataFrame({
    "station": _ids,
    "name": [_names[i] for i in _ids],
    "μ₀": [float(_idf.mu0.sel(station_id=i)) for i in _ids],
    "α": [float(_idf.alpha.sel(station_id=i)) for i in _ids],
    "100-yr 1 h": [float(_qq.sel(station_id=i, duration=1.0)) for i in _ids],
    "100-yr 24 h": [float(_qq.sel(station_id=i, duration=24.0)) for i in _ids],
})
for _col, _fmt in (("μ₀", "{:.2f}"), ("α", "{:.3f}"), ("100-yr 1 h", "{:.2f}"), ("100-yr 24 h", "{:.2f}")):
    _show[_col] = _show[_col].map(lambda v, fmt=_fmt: fmt.format(v))
_sh = q[q.station_id == "7028124"]
w(f"The shared year axis runs from {int(_da.year.min())} to {int(_da.year.max())} "
  f"({_da.sizes['year']} years). A year a station does not have is NaN, and the fit ignores it. "
  f"{'All three fits converge' if bool(_idf.converged.all()) else 'Not every fit converged'}. "
  "`idf_quantile` keeps `station_id` and adds `duration` (hours) and `period`. "
  "The 100-year intensities (mm/h):\n")
w(_show.to_markdown(index=False) + "\n")
w(f"Québec City's 100-year 1-hour intensity is {float(_qq.sel(station_id='701S001', duration=1.0)):.2f} mm/h, "
  "the same value as the independent d-GEV in section 5. "
  f"Sherbrooke A only covers {int(_sh.year.min())}–{int(_sh.year.max())}, so that level is estimated from {len(_sh)} years.\n")
w("## Caveats\n")
w("- ECCC annual maxima mix station histories (composite records); check metadata before inference.\n"
  "- The d-GEV assumes a common shape ξ across durations; the scaling test above is the check.\n"
  "- Wald intervals for 100-year levels can under-cover; prefer profile or bootstrap intervals.\n")
(DOCS / "tutorial_quebec_idf.md").write_text("\n".join(out))
print("\n".join(out))
